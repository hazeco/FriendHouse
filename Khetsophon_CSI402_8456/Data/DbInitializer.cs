            // เตรียมข้อมูลบันทึกกิจกรรมย้อนหลัง 90 วันและรายชั่วโมงสำหรับกราฟสถิติหน้า IT Dashboard เพื่อให้สัดส่วน INFO (สีน้ำเงิน) แสดงผลถูกต้องครบทั้งมุมมองรายวัน, 30 วัน และ 90 วัน
            if (!context.Systemlogs.Any(l => l.LogCode == "HIST-LOG-D090-1"))
            {
                // ค้นหาผู้ใช้ตัวอย่างสำหรับผูกกับบันทึกกิจกรรมประวัติ
                var histUser = context.Users.FirstOrDefault();
                // สร้างบันทึกกิจกรรมรายชั่วโมงย้อนหลัง 24 ชั่วโมง (เน้นระดับ INFO เป็นหลัก)
                for (int h = 1; h <= 24; h++)
                {
                    // คำนวณจำนวนบันทึกกิจกรรมในแต่ละชั่วโมง
                    int infoCountForHour = 4 + (h % 5);
                    // วนลูปสร้างบันทึกกิจกรรมในชั่วโมงนั้น
                    for (int k = 1; k <= infoCountForHour; k++)
                    {
                        // กำหนดรหัสบันทึกกิจกรรมรายชั่วโมง
                        string hCode = $"HIST-LOG-H{h:D2}-{k}";
                        // ตรวจสอบว่ามีรหัสบันทึกกิจกรรมนี้แล้วหรือไม่
                        if (!context.Systemlogs.Any(l => l.LogCode == hCode))
                        {
                            // เพิ่มบันทึกกิจกรรมรายชั่วโมงลงในฐานข้อมูล
                            context.Systemlogs.Add(new Systemlog
                            {
                                // กำหนดรหัสบันทึก
                                LogCode = hCode,
                                // กำหนดระดับเป็น INFO
                                LogLevel = "INFO",
                                // กำหนดโมดูลของกิจกรรม
                                Module = (k % 2 == 0) ? "auth.login" : "inventory.stock",
                                // กำหนดข้อความรายละเอียดกิจกรรม
                                Message = (k % 2 == 0)
                                    // ข้อความสำหรับกิจกรรมตรวจสอบเซสชัน
                                    ? $"ตรวจสอบสถานะเซสชันผู้ใช้งานประจำชั่วโมงที่ {h} สำเร็จ"
                                    // ข้อความสำหรับกิจกรรมซิงก์สต็อก
                                    : $"ซิงก์ข้อมูลสต็อกสินค้าหน้าร้านประจำชั่วโมงที่ {h} สำเร็จ",
                                // กำหนดรหัสผู้ใช้
                                UserId = histUser?.UserId,
                                // กำหนดวันเวลาของบันทึก
                                Timestamp = DateTime.UtcNow.AddHours(-h).AddMinutes(k * 5)
                            });
                        }
                    }
                }

                // สร้างบันทึกกิจกรรมรายวันย้อนหลัง 90 วัน รวมถึงวันนี้ (เน้นระดับ INFO 85-95% และมี WARNING/ERROR เล็กน้อยในบางวัน)
                for (int d = 0; d <= 90; d++)
                {
                    // กำหนดจำนวนบันทึกระดับ INFO ประจำวัน
                    int dailyInfoCount = d == 0 ? 20 : (6 + ((d * 3) % 7));
                    // วนลูปสร้างบันทึกระดับ INFO ในแต่ละวัน
                    for (int m = 1; m <= dailyInfoCount; m++)
                    {
                        // กำหนดรหัสบันทึกกิจกรรมรายวัน
                        string dCode = $"HIST-LOG-D{d:D3}-{m}";
                        // ตรวจสอบว่ามีรหัสบันทึกกิจกรรมนี้แล้วหรือไม่
                        if (!context.Systemlogs.Any(l => l.LogCode == dCode))
                        {
                            // เพิ่มบันทึกกิจกรรมรายวันลงในฐานข้อมูล
                            context.Systemlogs.Add(new Systemlog
                            {
                                // กำหนดรหัสบันทึก
                                LogCode = dCode,
                                // กำหนดระดับเป็น INFO
                                LogLevel = "INFO",
                                // กำหนดชื่อโมดูล
                                Module = (m % 3 == 0) ? "preorder.counter" : ((m % 2 == 0) ? "inventory.stock" : "auth.login"),
                                // กำหนดข้อความกิจกรรม
                                Message = d == 0
                                    // ข้อความกิจกรรมของวันปัจจุบัน
                                    ? $"บันทึกกิจกรรมระบบปกติประจำวัน ลำดับที่ {m}"
                                    // ข้อความกิจกรรมย้อนหลัง
                                    : $"บันทึกกิจกรรมระบบปกติประจำวันที่ย้อนหลัง {d} วัน ลำดับที่ {m}",
                                // กำหนดรหัสผู้ใช้
                                UserId = histUser?.UserId,
                                // กำหนดวันเวลาของกิจกรรม
                                Timestamp = d == 0
                                    // เวลาบันทึกสำหรับวันปัจจุบัน
                                    ? DateTime.UtcNow.AddMinutes(-(m * 15))
                                    // เวลาบันทึกสำหรับวันย้อนหลัง
                                    : DateTime.UtcNow.Date.AddDays(-d).AddHours(9 + (m % 10))
                            });
                        }
                    }

                    // เพิ่มรายการแจ้งเตือน WARNING เล็กน้อยในบางวัน (เช่น ทุก 6 วัน วันละ 1-2 รายการ)
                    if (d % 6 == 0)
                    {
                        // กำหนดรหัสบันทึกการแจ้งเตือน
                        string wCode = $"HIST-WARN-D{d:D3}";
                        // ตรวจสอบว่ามีรหัสบันทึกการแจ้งเตือนนี้แล้วหรือไม่
                        if (!context.Systemlogs.Any(l => l.LogCode == wCode))
                        {
                            // เพิ่มบันทึกการแจ้งเตือนลงในฐานข้อมูล
                            context.Systemlogs.Add(new Systemlog
                            {
                                // กำหนดรหัสบันทึก
                                LogCode = wCode,
                                // กำหนดระดับเป็น WARNING
                                LogLevel = "WARNING",
                                // กำหนดโมดูลของกิจกรรม
                                Module = "inventory.stock",
                                // กำหนดข้อความการแจ้งเตือน
                                Message = $"แจ้งเตือนสินค้าคงเหลือต่ำกว่าเกณฑ์ปลอดภัย ประจำรอบตรวจย้อนหลัง {d} วัน",
                                // กำหนดรหัสผู้ใช้
                                UserId = histUser?.UserId,
                                // กำหนดวันเวลาของการแจ้งเตือน
                                Timestamp = DateTime.UtcNow.Date.AddDays(-d).AddHours(14)
                            });
                        }
                    }

                    // เพิ่มรายการข้อผิดพลาด ERROR เล็กน้อยในบางวัน (เช่น ทุก 15 วัน วันละ 1 รายการ)
                    if (d % 15 == 0)
                    {
                        // กำหนดรหัสบันทึกข้อผิดพลาด
                        string eCode = $"HIST-ERR-D{d:D3}";
                        // ตรวจสอบว่ามีรหัสบันทึกข้อผิดพลาดนี้แล้วหรือไม่
                        if (!context.Systemlogs.Any(l => l.LogCode == eCode))
                        {
                            // เพิ่มบันทึกข้อผิดพลาดลงในฐานข้อมูล
                            context.Systemlogs.Add(new Systemlog
                            {
                                // กำหนดรหัสบันทึก
                                LogCode = eCode,
                                // กำหนดระดับเป็น ERROR
                                LogLevel = "ERROR",
                                // กำหนดโมดูลที่เกิดข้อผิดพลาด
                                Module = "auth.login",
                                // กำหนดข้อความข้อผิดพลาด
                                Message = $"ตรวจพบการกรอกรหัสผ่านไม่ถูกต้องจากผู้ใช้งานภายนอก ย้อนหลัง {d} วัน",
                                // กำหนดรหัสผู้ใช้เป็นค่าว่าง
                                UserId = null,
                                // กำหนดวันเวลาที่เกิดข้อผิดพลาด
                                Timestamp = DateTime.UtcNow.Date.AddDays(-d).AddHours(16)
                            });
                        }
                    }
                }
                // บันทึกกิจกรรมประวัติลงฐานข้อมูล
                context.SaveChanges();
            }
        }
        // ดักจับข้อผิดพลาดทั่วไปที่อาจเกิดขึ้นระหว่างการเตรียมข้อมูลเริ่มต้น
        catch (Exception)
        {
            // WHY: กลืนข้อผิดพลาดไว้ไม่ให้แอปพลิเคชันหยุดทำงานเมื่อฐานข้อมูลยังไม่ได้เปิดบริการในสภาพแวดล้อม Local
            // ระบบ Razor Views ทั้งหมดมีข้อมูลสำรอง Fallback Mock รองรับอยู่แล้ว
        }
    }
