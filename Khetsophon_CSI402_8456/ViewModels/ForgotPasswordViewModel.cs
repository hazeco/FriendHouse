using System.ComponentModel.DataAnnotations;

namespace Khetsophon_CSI402_8456.ViewModels;

// READ: ViewModel สำหรับแบบฟอร์มกู้คืนรหัสผ่านก่อนเข้าสู่ระบบ (Views/Account/ForgotPassword.cshtml)
// WHY: รองรับการยืนยันตัวตนด้วยอีเมลและเบอร์โทรศัพท์ เพื่อสร้างรหัสยืนยัน 6 หลักสำหรับตั้งรหัสผ่านใหม่โดยไม่ต้องพึ่งพาระบบส่งอีเมลภายนอก
public class ForgotPasswordViewModel
{
    // บังคับกรอกที่อยู่อีเมล
    [Required(ErrorMessage = "กรุณากรอกที่อยู่อีเมลที่ลงทะเบียนไว้")]
    // ตรวจสอบรูปแบบที่อยู่อีเมลให้ถูกต้องตามมาตรฐาน
    [EmailAddress(ErrorMessage = "รูปแบบที่อยู่อีเมลไม่ถูกต้อง")]
    // ป้ายกำกับชื่อฟิลด์สำหรับแสดงผลบนแบบฟอร์ม
    [Display(Name = "อีเมลบัญชีผู้ใช้")]
    // ที่อยู่อีเมลของบัญชีที่ต้องการกู้คืนรหัสผ่าน
    public string Email { get; set; } = string.Empty;

    // บังคับกรอกเบอร์โทรศัพท์
    [Required(ErrorMessage = "กรุณากรอกเบอร์โทรศัพท์ที่ลงทะเบียนไว้")]
    // ป้ายกำกับเบอร์โทรศัพท์สำหรับแสดงผลบนแบบฟอร์ม
    [Display(Name = "เบอร์โทรศัพท์ที่ลงทะเบียน")]
    // หมายเลขโทรศัพท์ที่ลงทะเบียนไว้คู่กับบัญชี
    public string Phone { get; set; } = string.Empty;

    // สถานะระบุว่าผ่านการตรวจสอบอีเมลและเบอร์โทรเพื่อออกรหัสยืนยันแล้วหรือไม่
    public bool IsCodeGenerated { get; set; }

    // รหัสยืนยัน 6 หลักที่ระบบสร้างขึ้นแสดงบนหน้าจอให้คัดลอกและกรอกอัตโนมัติ
    public string? GeneratedCode { get; set; }

    // ป้ายกำกับรหัสยืนยัน 6 หลักบนหน้าแบบฟอร์ม
    [Display(Name = "รหัสยืนยันกู้คืนรหัสผ่าน 6 หลัก")]
    // รหัสยืนยัน 6 หลักที่ผู้ใช้กรอกหรือกดปุ่มกรอกอัตโนมัติเพื่อยืนยันการตั้งรหัสผ่านใหม่
    public string? VerificationCode { get; set; }

    // กำหนดความยาวรหัสผ่านใหม่อย่างน้อย 6 ตัวอักษร
    [MinLength(6, ErrorMessage = "รหัสผ่านใหม่ต้องมีความยาวอย่างน้อย 6 ตัวอักษร")]
    // กำหนดชนิดข้อมูลเป็นรหัสผ่านเพื่อซ่อนตัวอักษรบนหน้าจอ
    [DataType(DataType.Password)]
    // ป้ายกำกับรหัสผ่านใหม่
    [Display(Name = "รหัสผ่านใหม่")]
    // รหัสผ่านใหม่ที่ต้องการตั้งหลังจากยืนยันรหัส 6 หลัก
    public string? NewPassword { get; set; }

    // ตรวจสอบว่าการยืนยันรหัสผ่านใหม่ตรงกับรหัสผ่านใหม่ที่ระบุ
    [Compare("NewPassword", ErrorMessage = "รหัสผ่านใหม่และการยืนยันรหัสผ่านไม่ตรงกัน")]
    // กำหนดชนิดข้อมูลเป็นรหัสผ่านเพื่อซ่อนตัวอักษรบนหน้าจอ
    [DataType(DataType.Password)]
    // ป้ายกำกับยืนยันรหัสผ่านใหม่
    [Display(Name = "ยืนยันรหัสผ่านใหม่")]
    // ยืนยันรหัสผ่านใหม่ให้ตรงกับรหัสผ่านใหม่
    public string? ConfirmNewPassword { get; set; }
}
